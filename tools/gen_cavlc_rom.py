#!/usr/bin/env python3
"""
Generate rtl/include/cavlc_tables.svh from c_model/src/cavlc.c.

The C tables are (len, bits) per symbol (ffmpeg layout); the decoder
needs codeword -> symbol. Each table becomes a casez over the MSB-first
lookahead window with '?' padding past the code length — synthesis sees
a priority decoder. Single source of truth: the C arrays are parsed,
never transcribed by hand (the x264 range_lps lesson).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "c_model" / "src" / "cavlc.c"
OUT = ROOT / "rtl" / "include" / "cavlc_tables.svh"


def parse_array(text: str, name: str) -> list[int]:
    """Flat int list of a 1-D initializer."""
    m = re.search(rf"{name}\[[^]]*\]\s*=\s*\{{(.*?)\n\}};", text, re.S)
    assert m, name
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1))]


def parse_array2(text: str, name: str) -> list[list[int]]:
    """Rows of a (possibly jagged) 2-D initializer."""
    m = re.search(rf"{name}\[[^]]*\]\[[^]]*\]\s*=\s*\{{(.*?)\n\}};",
                  text, re.S)
    assert m, name
    rows = re.findall(r"\{([^}]*)\}", m.group(1))
    return [[int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", r)]
            for r in rows]


def casez_lines(pairs, win, fmt_sym):
    """pairs: list of (length, bits, payload). Longest codes first so the
    priority order never lets a short prefix shadow a longer code."""
    lines = []
    for ln, bits, payload in sorted(pairs, key=lambda p: -p[0]):
        pat = format(bits, f"0{ln}b") + "?" * (win - ln)
        lines.append(f"      {win}'b{pat}: {fmt_sym(ln, payload)}")
    return lines


def main() -> int:
    text = SRC.read_text()

    ct_len2 = parse_array2(text, "coeff_token_len")
    ct_bits2 = parse_array2(text, "coeff_token_bits")
    cdc_len = parse_array(text, "chroma_dc_coeff_token_len")
    cdc_bits = parse_array(text, "chroma_dc_coeff_token_bits")
    tz_len2 = parse_array2(text, "total_zeros_len")
    tz_bits2 = parse_array2(text, "total_zeros_bits")
    ctz_len2 = parse_array2(text, "chroma_dc_total_zeros_len")
    ctz_bits2 = parse_array2(text, "chroma_dc_total_zeros_bits")
    run_len2 = parse_array2(text, "run_len")
    run_bits2 = parse_array2(text, "run_bits")

    def pad(rows, n):
        return [r + [0] * (n - len(r)) for r in rows]

    ct_len = [v for r in pad(ct_len2, 68) for v in r]
    ct_bits = [v for r in pad(ct_bits2, 68) for v in r]
    tz_len = [v for r in pad(tz_len2, 16) for v in r]
    tz_bits = [v for r in pad(tz_bits2, 16) for v in r]
    ctz_len = [v for r in pad(ctz_len2, 4) for v in r]
    ctz_bits = [v for r in pad(ctz_bits2, 4) for v in r]
    run_len = [v for r in pad(run_len2, 16) for v in r]
    run_bits = [v for r in pad(run_bits2, 16) for v in r]

    assert len(ct_len) == 4 * 68 and len(ct_bits) == 4 * 68, \
        (len(ct_len), len(ct_bits))
    assert len(tz_len) == 15 * 16 and len(run_len) == 7 * 16

    # ---- self-check: every codeword must decode to its own symbol under
    # longest-first priority matching (the casez semantics) ----
    def roundtrip(pairs, win):
        ordered = sorted(pairs, key=lambda q: -q[0])
        for ln, bits, payload in pairs:
            word = bits << (win - ln)          # zero tail
            hit = None
            for l2, b2, p2 in ordered:
                if (word >> (win - l2)) == b2:
                    hit = (l2, p2)
                    break
            assert hit == (ln, payload), \
                (f"shadowed code: len={ln} bits={bits:0{ln}b} "
                 f"-> {hit} expected {(ln, payload)}")

    for tab in range(4):
        pr = []
        for tc in range(17):
            for t1 in range(4):
                if t1 > tc:
                    continue
                i = tab * 68 + tc * 4 + t1
                if ct_len[i]:
                    pr.append((ct_len[i], ct_bits[i], (tc, t1)))
        roundtrip(pr, 16)
    for tname, lens, bitsv, nsub, nsym, win in [
            ("tz", tz_len, tz_bits, 15, 16, 9),
            ("ctz", ctz_len, ctz_bits, 3, 4, 3),
            ("run", run_len, run_bits, 7, 16, 11)]:
        for s in range(nsub):
            pr = [(lens[s * nsym + k], bitsv[s * nsym + k], k)
                  for k in range(nsym) if lens[s * nsym + k]]
            roundtrip(pr, win)
    print("self-check: all tables roundtrip clean")

    out = ["// AUTO-GENERATED by tools/gen_cavlc_rom.py — do not edit.",
           "// Source of truth: c_model/src/cavlc.c (clause 9.2 tables).",
           "`ifndef CAVLC_TABLES_SVH",
           "`define CAVLC_TABLES_SVH",
           ""]

    # ---- coeff_token: 4 nC classes + chroma DC, window 16 ----
    # C layout: index = tc*4 + t1 over 17*4 entries (tc 0..16, t1 0..3);
    # invalid combos have len 0.
    out.append("// coeff_token: {valid, total_coeff[4:0], t1[1:0], len[4:0]}")
    out.append("function automatic logic [12:0] cavlc_coeff_token(")
    out.append("    input logic [2:0] tab, input logic [15:0] win);")
    out.append("  logic [12:0] r;")
    out.append("  r = '0;")
    out.append("  unique case (tab)")
    for tab in range(4):
        pairs = []
        for tc in range(17):
            for t1 in range(4):
                if t1 > tc:
                    continue
                i = tab * 68 + tc * 4 + t1
                ln = ct_len[i]
                if ln == 0:
                    continue
                pairs.append((ln, ct_bits[i], (tc, t1)))
        out.append(f"    3'd{tab}: casez (win)")
        out += casez_lines(
            pairs, 16,
            lambda ln, p: f"r = {{1'b1, 5'd{p[0]}, 2'd{p[1]}, 5'd{ln}}};")
        out.append("      default: r = '0;")
        out.append("    endcase")
    # chroma DC table = tab 4
    pairs = []
    for tc in range(5):
        for t1 in range(4):
            if t1 > tc:
                continue
            i = tc * 4 + t1
            ln = cdc_len[i]
            if ln == 0:
                continue
            pairs.append((ln, cdc_bits[i], (tc, t1)))
    out.append("    3'd4: casez (win)")
    out += casez_lines(
        pairs, 16,
        lambda ln, p: f"r = {{1'b1, 5'd{p[0]}, 2'd{p[1]}, 5'd{ln}}};")
    out.append("      default: r = '0;")
    out.append("    endcase")
    out.append("    default: r = '0;")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")
    out.append("")

    # ---- total_zeros: 15 luma subtables (idx total_coeff-1), window 9 ----
    out.append("// total_zeros: {valid, tz[3:0], len[3:0]}")
    out.append("function automatic logic [8:0] cavlc_total_zeros(")
    out.append("    input logic [3:0] tc_m1, input logic [8:0] win);")
    out.append("  logic [8:0] r;")
    out.append("  r = '0;")
    out.append("  unique case (tc_m1)")
    for t in range(15):
        pairs = []
        for tz in range(16):
            ln = tz_len[t * 16 + tz]
            if ln == 0:
                continue
            pairs.append((ln, tz_bits[t * 16 + tz], tz))
        out.append(f"    4'd{t}: casez (win)")
        out += casez_lines(
            pairs, 9, lambda ln, p: f"r = {{1'b1, 4'd{p}, 4'd{ln}}};")
        out.append("      default: r = '0;")
        out.append("    endcase")
    out.append("    default: r = '0;")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")
    out.append("")

    # ---- chroma DC total_zeros: 3 subtables, window 3 ----
    out.append("// chroma DC total_zeros: {valid, tz[1:0], len[1:0]}")
    out.append("function automatic logic [4:0] cavlc_cdc_total_zeros(")
    out.append("    input logic [1:0] tc_m1, input logic [2:0] win);")
    out.append("  logic [4:0] r;")
    out.append("  r = '0;")
    out.append("  unique case (tc_m1)")
    for t in range(3):
        pairs = []
        for tz in range(4):
            ln = ctz_len[t * 4 + tz]
            if ln == 0:
                continue
            pairs.append((ln, ctz_bits[t * 4 + tz], tz))
        out.append(f"    2'd{t}: casez (win)")
        out += casez_lines(
            pairs, 3, lambda ln, p: f"r = {{1'b1, 2'd{p}, 2'd{ln}}};")
        out.append("      default: r = '0;")
        out.append("    endcase")
    out.append("    default: r = '0;")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")
    out.append("")

    # ---- run_before: 7 subtables (zeros_left clamped to 7), window 11 ----
    out.append("// run_before: {valid, run[3:0], len[3:0]}")
    out.append("function automatic logic [8:0] cavlc_run_before(")
    out.append("    input logic [2:0] zl_m1, input logic [10:0] win);")
    out.append("  logic [8:0] r;")
    out.append("  r = '0;")
    out.append("  unique case (zl_m1)")
    for z in range(7):
        pairs = []
        for run in range(16):
            ln = run_len[z * 16 + run]
            if ln == 0:
                continue
            pairs.append((ln, run_bits[z * 16 + run], run))
        out.append(f"    3'd{z}: casez (win)")
        out += casez_lines(
            pairs, 11, lambda ln, p: f"r = {{1'b1, 4'd{p}, 4'd{ln}}};")
        out.append("      default: r = '0;")
        out.append("    endcase")
    out.append("    default: r = '0;")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")

    # ---- intra CBP mapping (Table 9-4 intra column) + 4x4 zigzag ----
    cbp_tab = parse_array(text, "golomb_to_intra4x4_cbp")
    assert len(cbp_tab) == 48
    out.append("")
    out.append("// Table 9-4 intra CBP mapping (ue code -> cbp)")
    out.append("function automatic logic [5:0] cavlc_intra_cbp(")
    out.append("    input logic [5:0] code);")
    out.append("  logic [5:0] r;")
    out.append("  unique case (code)")
    for i, v in enumerate(cbp_tab):
        out.append(f"    6'd{i}: r = 6'd{v};")
    out.append("    default: r = 6'd63;          // invalid marker")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")

    # ---- inter CBP mapping (Table 9-4 inter column, decoder.c) ----
    dtext = (ROOT / "c_model" / "src" / "decoder.c").read_text()
    icbp = parse_array(dtext, "golomb_to_inter_cbp")
    assert len(icbp) == 48
    out.append("")
    out.append("// Table 9-4 inter CBP mapping (ue code -> cbp)")
    out.append("function automatic logic [5:0] cavlc_inter_cbp(")
    out.append("    input logic [5:0] code);")
    out.append("  logic [5:0] r;")
    out.append("  unique case (code)")
    for i, v in enumerate(icbp):
        out.append(f"    6'd{i}: r = 6'd{v};")
    out.append("    default: r = 6'd63;          // invalid marker")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")

    ttext = (ROOT / "c_model" / "src" / "transform.c").read_text()
    zz = parse_array(ttext, "h264_zigzag4x4")
    assert len(zz) == 16 and sorted(zz) == list(range(16))
    out.append("")
    out.append("// 4x4 zigzag scan -> raster position")
    out.append("function automatic logic [3:0] zz4(input logic [3:0] s);")
    out.append("  logic [3:0] r;")
    out.append("  unique case (s)")
    for i, v in enumerate(zz):
        out.append(f"    4'd{i}: r = 4'd{v};")
    out.append("  endcase")
    out.append("  return r;")
    out.append("endfunction")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    out.append("")
    out.append("`endif  // CAVLC_TABLES_SVH")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
