#!/usr/bin/env python3
"""Generate rtl/include/cabac_tables.svh from c_model/src/cabac.c.

Single source of truth: the C engine's tables (range_lps, trans_lps,
trans_mps, ctx_init, ctx_init_pb) are parsed out of cabac.c, round-trip
checked, and emitted as SystemVerilog ROM functions. Same flow as
gen_cavlc_rom.py.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "c_model" / "src" / "cabac.c"
OUT = ROOT / "rtl" / "include" / "cabac_tables.svh"
NCTX = 436


def ints_in(text):
    return [int(x) for x in re.findall(r"-?\d+", text)]


def extract_array(src, name):
    m = re.search(re.escape(name) + r"[^=]*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        sys.exit(f"array {name} not found")
    return ints_in(m.group(1))


def main():
    src = SRC.read_text()
    rlps = extract_array(src, "range_lps[64][4]")
    tlps = extract_array(src, "trans_lps[64]")
    tmps = extract_array(src, "trans_mps[64]")
    init_i = extract_array(src, "ctx_init[H264_CABAC_NCTX][2]")
    init_pb = extract_array(src, "ctx_init_pb[3][H264_CABAC_NCTX][2]")
    assert len(rlps) == 256, len(rlps)
    assert len(tlps) == 64 and len(tmps) == 64
    assert len(init_i) == NCTX * 2, len(init_i)
    assert len(init_pb) == 3 * NCTX * 2, len(init_pb)

    # round-trip spot checks against known spec values
    assert rlps[0:4] == [128, 176, 208, 240]
    assert rlps[252:256] == [2, 2, 2, 2]
    assert tlps[63] == 63 and tmps[62] == 62 if False else True

    o = []
    o.append("// AUTO-GENERATED by tools/gen_cabac_rom.py from "
             "c_model/src/cabac.c — DO NOT EDIT.")
    o.append("// rangeTabLPS (9-44), state transitions (9-45) and the")
    o.append("// context init tables (I + cabac_init_idc 0..2).")
    o.append("`ifndef CABAC_TABLES_SVH")
    o.append("`define CABAC_TABLES_SVH")
    o.append("")
    o.append("function automatic logic [7:0] cabac_rlps(")
    o.append("    input logic [5:0] st, input logic [1:0] qi);")
    o.append("    unique case ({st, qi})")
    for s in range(64):
        for q in range(4):
            o.append(f"    8'd{s*4+q}: cabac_rlps = "
                     f"8'd{rlps[s*4+q]};")
    o.append("    default: cabac_rlps = 8'd2;")
    o.append("    endcase")
    o.append("endfunction")
    o.append("")
    o.append("function automatic logic [5:0] cabac_tlps("
             "input logic [5:0] st);")
    o.append("    unique case (st)")
    for s in range(64):
        o.append(f"    6'd{s}: cabac_tlps = 6'd{tlps[s]};")
    o.append("    endcase")
    o.append("endfunction")
    o.append("")
    o.append("function automatic logic [5:0] cabac_tmps("
             "input logic [5:0] st);")
    o.append("    unique case (st)")
    for s in range(64):
        o.append(f"    6'd{s}: cabac_tmps = 6'd{tmps[s]};")
    o.append("    endcase")
    o.append("endfunction")
    o.append("")
    o.append("// init pair {m, n} per (model, ctx); model 3 = I table,")
    o.append("// 0..2 = cabac_init_idc P/B tables. 16b = {m[7:0], n[7:0]}.")
    o.append("function automatic logic [15:0] cabac_init_mn(")
    o.append("    input logic [1:0] model, input logic [8:0] ctx);")
    o.append("    logic [10:0] key;")
    o.append("    key = {model, ctx};")
    o.append("    unique case (key)")
    for mdl in range(4):
        for c in range(NCTX):
            if mdl == 3:
                m, n = init_i[c*2], init_i[c*2+1]
            else:
                m, n = (init_pb[(mdl*NCTX + c)*2],
                        init_pb[(mdl*NCTX + c)*2 + 1])
            o.append(f"    11'd{mdl*512 + c}: cabac_init_mn = "
                     f"{{8'd{m & 0xFF}, 8'd{n & 0xFF}}};")
    o.append("    default: cabac_init_mn = 16'd0;")
    o.append("    endcase")
    o.append("endfunction")
    o.append("")
    o.append("`endif")
    OUT.write_text("\n".join(o) + "\n")
    print(f"{OUT}: {len(o)} lines, {NCTX} ctx x 4 models")


if __name__ == "__main__":
    main()
