static int clip3i(int lo, int hi, int v) {
    return v < lo ? lo : (v > hi ? hi : v);
}

static uint32_t next_bit(cabac_t *c) {
    if (c->pos >= c->size) {
        if (++c->overread > 32) c->error = 1;
        return 0;
    }
    uint32_t b = (uint32_t)(c->data[c->pos] >> (7 - c->bit)) & 1u;
    if (++c->bit == 8) {
        c->bit = 0;
        c->pos++;
    }
    return b;
}

void cabac_init(cabac_t *c, const uint8_t *data, size_t size, size_t pos,
                int slice_qp) {
    memset(c, 0, sizeof(*c));
    c->data = data;
    c->size = size;
    c->pos = pos;
    for (int i = 0; i < H264_CABAC_NCTX; i++) {
        int pre = clip3i(1, 126,
                         ((ctx_init[i][0] * clip3i(0, 51, slice_qp)) >> 4) +
                         ctx_init[i][1]);
        if (pre <= 63) {
            c->pstate[i] = (uint8_t)(63 - pre);
            c->mps[i] = 0;
        } else {
            c->pstate[i] = (uint8_t)(pre - 64);
            c->mps[i] = 1;
        }
    }
    c->range = 510;
    c->value = 0;
    for (int i = 0; i < 9; i++) c->value = (c->value << 1) | next_bit(c);
}

static void renorm(cabac_t *c) {
    while (c->range < 256) {
        c->range <<= 1;
        c->value = (c->value << 1) | next_bit(c);
    }
}

static int cabac_dbg(void) {
    static int v = -1;
    if (v < 0) v = getenv("CABAC_DBG") ? 1 : 0;
    return v;
}

int cabac_decision(cabac_t *c, int ctx) {
    uint32_t r0 = c->range, v0 = c->value;
    int ps0 = c->pstate[ctx], m0 = c->mps[ctx];
    uint32_t rlps = range_lps[c->pstate[ctx]][(c->range >> 6) - 4];
    int bin;
    c->range -= rlps;
    if (c->value < c->range) {
        bin = c->mps[ctx];
        c->pstate[ctx] = trans_mps[c->pstate[ctx]];
    } else {
        c->value -= c->range;
        c->range = rlps;
        bin = !c->mps[ctx];
        if (c->pstate[ctx] == 0) c->mps[ctx] ^= 1;
        c->pstate[ctx] = trans_lps[c->pstate[ctx]];
    }
    renorm(c);
    if (cabac_dbg()) {
        fprintf(stderr, "DEC ctx=%d ps=%d mps=%d r=%u v=%u -> bin=%d rlps=%u\n",
                ctx, ps0, m0, r0, v0, bin, rlps);
    }
    return bin;
}

int cabac_bypass(cabac_t *c) {
    c->value = (c->value << 1) | next_bit(c);
    if (c->value >= c->range) {
        c->value -= c->range;
        return 1;
    }
    return 0;
}

int cabac_terminate(cabac_t *c) {
    c->range -= 2;
    if (c->value >= c->range) {
        return 1;
    }
    renorm(c);
    return 0;
}

size_t cabac_byte_pos(const cabac_t *c) {
    return c->bit ? c->pos + 1 : c->pos;
}
